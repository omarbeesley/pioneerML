"""
Generate four PURITY mixed datasets from the train/val/eval unmixed splits:
  1. two_channel_training   : mixed pie/michel (uses *_train unmixed parquets)
  2. two_channel_validation : mixed pie/michel, same parameters as training (uses *_val)
  3. pie_benchmark_eval     : 'pie' mode (uses *_eval)
  4. pimu_benchmark_eval    : 'michel' mode (uses *_eval)

Each mixer instance reuses the ROOT-derived parquets generated by
generate_unmixed.py. The eval splits are disjoint at the source-file level
from train/val splits, so benchmark numbers reflect held-out events.

Two pileup-mixer config blocks:
  - TRAIN_VAL_OPTS : shared between training and validation
  - BENCHMARK_OPTS : shared between pie and pimu eval benchmarks
There are no settings shared across all four jobs.

Usage:
    python generate_benchmarks.py                       # all four
    python generate_benchmarks.py --only training       # one of: training|validation|pie|pimu
"""
import argparse
import os
import sys

import pyarrow as pa
import pyarrow.parquet as pq

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from unified_reco.pileup_mixer import PileupMixer

DATA_DIR = "/data/raid3/eliza7/PIONEER/data/ML_TEST/scratch_pipeline/unmixed_split/"
RECO_DIR = "/data/raid3/eliza7/PIONEER/data/ML_TEST/scratch_pipeline/mixed_standard/"

# Per-split unmixed parquets produced by generate_unmixed.py
SPLIT_FILES = {
    "train": dict(
        michel=os.path.join(DATA_DIR, "unmixed_michel_train.parquet"),
        pie   =os.path.join(DATA_DIR, "unmixed_pie_train.parquet"),
    ),
    "val": dict(
        michel=os.path.join(DATA_DIR, "unmixed_michel_val.parquet"),
        pie   =os.path.join(DATA_DIR, "unmixed_pie_val.parquet"),
    ),
    "eval": dict(
        michel=os.path.join(DATA_DIR, "unmixed_michel_eval.parquet"),
        pie   =os.path.join(DATA_DIR, "unmixed_pie_eval.parquet"),
    ),
}

# Pileup-mixer settings shared by training and validation (the two 'mixed' jobs).
TRAIN_VAL_OPTS = dict(
    biased_fraction=0.1,     # user setting
    biased_sigma=20.0,       # user setting
    cal_only_fraction=0.5,   # user setting — heavy calo pileup augmentation
    radio_rate=2e7,
    enforce_window=True,     # retry until primary positron survives the readout window
    trigger_gap_ns=2.0,
    pie_mix_fraction=0.2,    # 80% michel / 20% pie — oversample hard michel events
    max_reroll=4,            # cap retries; some events fall through with htp=0
)

# Pileup-mixer settings shared by pie and pimu eval benchmarks.
# EVAL IS UNBIASED: no biased/cal-only injection (must not carry train/val augmentation).
BENCHMARK_OPTS = dict(
    biased_fraction=0.0,
    biased_sigma=100.0,
    cal_only_fraction=0.0,   # user setting — eval must not have train/val biases
    radio_rate=2e7,
    enforce_window=False,
    trigger_gap_ns=2.0,
)


def _job_specs(args):
    """Build the four job specifications using CLI-controlled event counts."""
    return {
        "training": dict(
            split="train",
            mode="mixed",
            num_events=args.num_train,
            opts=TRAIN_VAL_OPTS,
            out=os.path.join(RECO_DIR, "training_5_11", "data.parquet"),
        ),
        "validation": dict(
            split="val",
            mode="mixed",
            num_events=args.num_val,
            opts=TRAIN_VAL_OPTS,
            out=os.path.join(RECO_DIR, "validation_5_11", "data.parquet"),
        ),
        "pie": dict(
            split="eval",
            mode="pie",
            num_events=args.num_eval,
            opts=BENCHMARK_OPTS,
            out=os.path.join(RECO_DIR, "pie_benchmark_5_11", "data.parquet"),
        ),
        "pimu": dict(
            split="eval",
            mode="michel",
            num_events=args.num_eval,
            opts=BENCHMARK_OPTS,
            out=os.path.join(RECO_DIR, "pimu_benchmark_5_11", "data.parquet"),
        ),
    }


def run_job(mixer, name, spec, chunk_size=100_000):
    """Generate `spec['num_events']` events in `chunk_size`-row pieces and
    append each as a row-group to a single parquet file. Bounds peak RAM to
    roughly the cost of one chunk (DataFrame + transient pyarrow Table)."""
    out = spec["out"]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    n_total = spec["num_events"]

    print(f"\n=== [{name}] split={spec['split']} mode={spec['mode']} "
          f"n={n_total}  chunk={chunk_size}  -> {out}", flush=True)

    writer = None
    schema = None
    n_done = 0
    while n_done < n_total:
        n_chunk = min(chunk_size, n_total - n_done)
        df = mixer.generate_batch(n_chunk, mode=spec["mode"], **spec["opts"])
        table = pa.Table.from_pandas(df)

        if writer is None:
            schema = table.schema
            writer = pq.ParquetWriter(out, schema)
        else:
            # Force schema match in case pyarrow infers slightly different
            # types between chunks (e.g. empty arrays in some rows).
            table = table.cast(schema, safe=False)

        writer.write_table(table)
        n_done += len(df)
        del df, table          # release peak RAM before the next chunk
        print(f"    [{name}] {n_done}/{n_total}", flush=True)

    if writer is not None:
        writer.close()
    print(f"    wrote {n_done} rows to {out}", flush=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--only",
                        choices=["training", "validation", "pie", "pimu"],
                        default=None,
                        help="Run a single job instead of all four.")
    parser.add_argument("--num_train", type=int, default=10000000)
    parser.add_argument("--num_val",   type=int, default=100000)
    parser.add_argument("--num_eval",  type=int, default=1000000)
    parser.add_argument("--chunk_size", type=int, default=100_000,
                        help="Events per parquet row-group; controls peak RAM.")
    parser.add_argument("--out_dir", type=str, default=None,
                        help="Override RECO_DIR output base (for sharded/parallel mixing).")
    parser.add_argument("--seed", type=int, default=None,
                        help="Seed the numpy RNG (use a distinct value per parallel shard).")
    args = parser.parse_args()

    if args.seed is not None:
        import numpy as _np
        _np.random.seed(args.seed & 0xFFFFFFFF)
    if args.out_dir:
        global RECO_DIR
        RECO_DIR = args.out_dir

    specs = _job_specs(args)
    selected = [args.only] if args.only else list(specs.keys())

    # Group jobs by source split so we instantiate one PileupMixer per split.
    by_split = {}
    for name in selected:
        by_split.setdefault(specs[name]["split"], []).append(name)

    for split, names in by_split.items():
        files = SPLIT_FILES[split]
        for p in (files["michel"], files["pie"]):
            if not os.path.exists(p):
                raise FileNotFoundError(
                    f"Missing unmixed parquet for split '{split}': {p}\n"
                    f"Run generate_unmixed.py first."
                )
        print(f"\n--- Loading PileupMixer for split={split} "
              f"(michel={files['michel']}, pie={files['pie']})", flush=True)
        mixer = PileupMixer(michel_path=files["michel"], pie_path=files["pie"],
                            lut_dir="/data/raid3/eliza7/PIONEER/data/ML_TEST")
        for name in names:
            run_job(mixer, name, specs[name], chunk_size=args.chunk_size)


if __name__ == "__main__":
    main()
